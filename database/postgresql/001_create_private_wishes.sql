-- Future use: fresh connection, psql -X -v ON_ERROR_STOP=1 -f <this-file>.
-- First installation only: an existing schema/object causes an error, never replacement or repair.
-- PostgreSQL UTF8 required; Supabase project database already exists (usually named postgres).
BEGIN;
SET LOCAL search_path = pg_catalog;
SET LOCAL lock_timeout = '10s';
DO $guard$
BEGIN
    IF current_setting('server_encoding') <> 'UTF8' THEN
        RAISE EXCEPTION 'UTF8 database is required';
    END IF;
END $guard$;

CREATE SCHEMA birthday_private;
REVOKE ALL ON SCHEMA birthday_private FROM PUBLIC;

-- Count UTF-16 code units, not UTF8 bytes or PostgreSQL Unicode characters.
-- Supplementary characters use two units, BMP characters one. Empty text uses zero.
CREATE FUNCTION birthday_private.utf16_length(value text) RETURNS integer
LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE
SET search_path = pg_catalog
AS $function$
    SELECT COALESCE(sum(CASE WHEN ascii(c) > 65535 THEN 2 ELSE 1 END), 0)::integer
    FROM regexp_split_to_table(value, '') AS chars(c) WHERE c <> ''
$function$;
REVOKE ALL ON FUNCTION birthday_private.utf16_length(text) FROM PUBLIC;

CREATE TABLE birthday_private.wishes
(
    wish_id bigint GENERATED BY DEFAULT AS IDENTITY
        (SEQUENCE NAME birthday_private.wishes_wish_id_seq START WITH 1 INCREMENT BY 1)
        CONSTRAINT pk_wishes PRIMARY KEY,
    content text NOT NULL,
    created_at timestamptz(6) NOT NULL DEFAULT clock_timestamp(),
    created_at_100ns_remainder smallint NOT NULL DEFAULT 0,
    is_read boolean NOT NULL DEFAULT false,
    source text NOT NULL DEFAULT '王若溪大王生日网站',
    CONSTRAINT ck_wishes_content_length CHECK (birthday_private.utf16_length(content) <= 2000),
    CONSTRAINT ck_wishes_source_length CHECK (birthday_private.utf16_length(source) <= 100),
    -- Exact original database rule: remove TAB/LF/CR, then trim ASCII spaces. Not a generic TRIM shortcut.
    CONSTRAINT ck_wishes_content_not_blank CHECK (length(translate(content, chr(9) || chr(10) || chr(13) || ' ', '')) > 0),
    CONSTRAINT ck_wishes_source_not_blank CHECK (length(translate(source, chr(9) || chr(10) || chr(13) || ' ', '')) > 0),
    CONSTRAINT ck_wishes_100ns_remainder CHECK (created_at_100ns_remainder BETWEEN 0 AND 9),
    CONSTRAINT ck_wishes_created_at_range CHECK (isfinite(created_at)
        AND created_at >= TIMESTAMPTZ '0001-01-01 00:00:00+00'
        AND created_at <= TIMESTAMPTZ '9999-12-31 23:59:59.999999+00')
);

-- Logical CreatedAt DESC, WishId DESC. CreatedAt has TWO physical components to retain 100ns ordering.
CREATE INDEX ix_wishes_created_at_wish_id ON birthday_private.wishes
    (created_at DESC, created_at_100ns_remainder DESC, wish_id DESC);
CREATE INDEX ix_wishes_unread_created_at ON birthday_private.wishes
    (created_at DESC, created_at_100ns_remainder DESC, wish_id DESC) WHERE is_read = false;

REVOKE ALL ON TABLE birthday_private.wishes FROM PUBLIC;
REVOKE ALL ON SEQUENCE birthday_private.wishes_wish_id_seq FROM PUBLIC;
-- Supabase roles might not exist on a standalone local test instance.
DO $permissions$
DECLARE role_name text;
BEGIN
    FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN
            EXECUTE format('REVOKE ALL ON SCHEMA birthday_private FROM %I', role_name);
            EXECUTE format('REVOKE ALL ON TABLE birthday_private.wishes FROM %I', role_name);
            EXECUTE format('REVOKE ALL ON SEQUENCE birthday_private.wishes_wish_id_seq FROM %I', role_name);
            EXECUTE format('REVOKE ALL ON FUNCTION birthday_private.utf16_length(text) FROM %I', role_name);
        END IF;
    END LOOP;
END $permissions$;
COMMIT;
