-- Self-contained Supabase bootstrap for the GitHub Pages wish mailbox.
-- Run once in the Supabase SQL Editor. It creates the private schema/table and the public RPC.
-- Safe to re-run: every object uses IF NOT EXISTS / CREATE OR REPLACE.
BEGIN;

CREATE SCHEMA IF NOT EXISTS birthday_private;

CREATE TABLE IF NOT EXISTS birthday_private.wishes
(
    wish_id bigint GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT pk_wishes PRIMARY KEY,
    content text NOT NULL,
    created_at timestamptz(6) NOT NULL DEFAULT clock_timestamp(),
    created_at_100ns_remainder smallint NOT NULL DEFAULT 0,
    is_read boolean NOT NULL DEFAULT false,
    source text NOT NULL DEFAULT '王若溪大王生日网站',
    CONSTRAINT ck_wishes_content_length CHECK (char_length(content) <= 2000),
    CONSTRAINT ck_wishes_source_length CHECK (char_length(source) <= 100),
    CONSTRAINT ck_wishes_content_not_blank CHECK (content ~ '[^[:space:]]'),
    CONSTRAINT ck_wishes_source_not_blank CHECK (source ~ '[^[:space:]]'),
    CONSTRAINT ck_wishes_100ns_remainder CHECK (created_at_100ns_remainder BETWEEN 0 AND 9)
);

CREATE INDEX IF NOT EXISTS ix_wishes_created_at_wish_id
    ON birthday_private.wishes (created_at DESC, created_at_100ns_remainder DESC, wish_id DESC);

CREATE INDEX IF NOT EXISTS ix_wishes_unread_created_at
    ON birthday_private.wishes (created_at DESC, created_at_100ns_remainder DESC, wish_id DESC)
    WHERE is_read = false;

CREATE OR REPLACE FUNCTION public.create_wish(p_content text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
DECLARE
    saved birthday_private.wishes%ROWTYPE;
BEGIN
    IF p_content IS NULL OR p_content !~ '[^[:space:]]' THEN
        RAISE EXCEPTION 'content is required' USING ERRCODE = '22023';
    END IF;
    IF char_length(p_content) > 2000 THEN
        RAISE EXCEPTION 'content is too long' USING ERRCODE = '22001';
    END IF;

    INSERT INTO birthday_private.wishes (content)
    VALUES (p_content)
    RETURNING * INTO saved;

    RETURN jsonb_build_object(
        'wishId', saved.wish_id,
        'createdAt', to_char(saved.created_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"+00:00"'),
        'isRead', saved.is_read,
        'source', saved.source
    );
END;
$function$;

REVOKE ALL ON FUNCTION public.create_wish(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.create_wish(text) TO anon;

-- Make the new RPC visible to PostgREST immediately.
NOTIFY pgrst, 'reload schema';

COMMIT;
